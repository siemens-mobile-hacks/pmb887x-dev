#!/usr/bin/env perl
use strict;
use warnings;

use File::Spec;
use FindBin qw($RealBin);
use lib $RealBin;
use DspMapArchive qw(read_member);

my %classes = (
	'complete,0051,0000,0052,0053' => 0,
	'complete,0051,0000,0000,0053' => 1,
	'trap-complete,0051,0054,0052,0053' => 2,
	'timeout,FFFF,FFFF,FFFF,FFFF' => 3,
);

my $archive_path = File::Spec->catfile($RealBin, 'hardware-maps.pack.gz');
my $output_path = File::Spec->catfile($RealBin, 'hardware-map-classes.inc');
my @lines = split /\n/, read_member($archive_path, 'hardware-map.csv');
die "$archive_path: invalid raw map header\n" unless shift(@lines) eq 'opcode,outcome,entered,trap,post,done';
die "$archive_path: expected 65536 opcode records\n" unless @lines == 0x10000;

my @bytes = (0) x 0x4000;
for my $opcode (0 .. 0xFFFF) {
	my ($record_opcode, $outcome) = split /,/, $lines[$opcode], 2;
	die sprintf("%s: opcode %04X is out of order\n", $archive_path, $opcode) unless hex($record_opcode) == $opcode;
	my $class = $classes{$outcome};
	die sprintf("%s: opcode %04X has unknown outcome %s\n", $archive_path, $opcode, $outcome) unless defined $class;
	$bytes[$opcode >> 2] |= $class << (($opcode & 3) * 2);
}

open my $output, '>', $output_path or die "Cannot write $output_path: $!\n";
print {$output} "// Generated by pack_classes.pl from the PMB8876 hardware-map.csv in hardware-maps.pack.gz.\n";
print {$output} "static const uint8_t DSP_OPCODE_HARDWARE_CLASSES[] = {\n";
for (my $offset = 0; $offset < @bytes; $offset += 16) {
	print {$output} "\t", join(', ', map { sprintf '0x%02x', $_ } @bytes[$offset .. $offset + 15]), ",\n";
}
print {$output} "};\n";
close $output or die "Cannot close $output_path: $!\n";
