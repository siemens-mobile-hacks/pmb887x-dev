#!/usr/bin/env perl
use strict;
use warnings;

use File::Spec;
use FindBin qw($RealBin);
use lib $RealBin;
use DspMapArchive qw(read_member);

my %outcome_codes = (complete => 0, 'trap-complete' => 1, timeout => 2, 'trap-timeout' => 3, 'unsafe-skip' => 4);
my $family_count = 19;
my $block_words = 256;

sub fnv1a_words {
	my ($hash, @words) = @_;
	for my $word (@words) {
		for my $byte ($word & 0xFF, $word >> 8) {
			$hash ^= $byte;
			$hash = ($hash * 0x01000193) & 0xFFFFFFFF;
		}
	}
	return $hash;
}

my $clear = @ARGV == 1 && $ARGV[0] eq '--clear';
die "usage: $0 [--clear]\n" if @ARGV && !$clear;

my $archive_path = File::Spec->catfile($RealBin, 'hardware-maps.pack.gz');
my $output_path = File::Spec->catfile($RealBin, 'expansion-map-hashes.inc');
open my $output, '>', $output_path or die "Cannot write $output_path: $!\n";
if ($clear) {
	print {$output} "// Generated by pack_expansion_hashes.pl --clear for a hardware capture.\n";
	print {$output} "#define DSP_EXPANSION_HARDWARE_HASH_FAMILIES 0\n";
	print {$output} "static const uint32_t DSP_EXPANSION_HARDWARE_HASHES[1][0x10000 / $block_words];\n";
	close $output or die "Cannot close $output_path: $!\n";
	exit 0;
}
print {$output} "// Generated by pack_expansion_hashes.pl from the PMB8876 expansion maps in hardware-maps.pack.gz.\n";
print {$output} "#define DSP_EXPANSION_HARDWARE_HASH_FAMILIES $family_count\n";
print {$output} "static const uint32_t DSP_EXPANSION_HARDWARE_HASHES[$family_count][0x10000 / $block_words] = {\n";
for my $family (0 .. $family_count - 1) {
	my $name = sprintf 'expansion-family-%02u-map.csv', $family;
	my @lines = split /\n/, read_member($archive_path, $name);
	splice @lines, 0, 2;
	die "$name: expected 65536 records\n" unless @lines == 0x10000;
	my @hashes;
	my $hash;
	for my $expansion (0 .. 0xFFFF) {
		my ($record_family, $record_expansion, $outcome, @words) = split /,/, $lines[$expansion];
		die "$name: record $expansion is out of order\n"
			unless $record_family == $family && hex($record_expansion) == $expansion;
		die "$name: unknown outcome $outcome\n" unless exists $outcome_codes{$outcome};
		die "$name: record $expansion has " . scalar(@words) . " words\n" unless @words == 24;
		$hash = 0x811C9DC5 if ($expansion % $block_words) == 0;
		$hash = fnv1a_words($hash, $expansion, $outcome_codes{$outcome}, map { hex } @words);
		push @hashes, $hash if ($expansion % $block_words) == $block_words - 1;
	}
	print {$output} "\t{\n";
	for (my $i = 0; $i < @hashes; $i += 8) {
		print {$output} "\t\t", join(', ', map { sprintf '0x%08x', $_ } @hashes[$i .. $i + 7]), ",\n";
	}
	print {$output} "\t},\n";
}
print {$output} "};\n";
close $output or die "Cannot close $output_path: $!\n";
