#!/usr/bin/env perl
use warnings;
use strict;
use File::Basename;
use lib dirname(__FILE__).'/lib';
use Sie::CFI;
use Sie::Utils;

my $output = "";
open my $output_fp, ">", \$output or die "open(output): $!";
select $output_fp;

print qq|/* Autogenerated by $0 */\n#include "qemu/osdep.h"\n#include "parts.h"\n\n|;

my @flashes;
for my $info (Sie::CFI::loadFlashes()) {

	my $var_name = sprintf("flash_%04x_%04x", $info->{vid}, $info->{pid});

	print "static const uint8_t ${var_name}_cfi[] = {\n";
	print dumpHex("\t", $info->{cfi_bin});
	print "};\n";

	print "static const uint8_t ${var_name}_pri[] = {\n";
	print dumpHex("\t", $info->{pri_bin});
	print "};\n";

	my @flash_struct = (
		vid			=> sprintf("0x%04X", $info->{vid}),
		pid			=> sprintf("0x%04X", $info->{pid}),
		cfi			=> "${var_name}_cfi",
		cfi_size	=> "ARRAY_SIZE(${var_name}_cfi)",
		pri			=> "${var_name}_pri",
		pri_size	=> "ARRAY_SIZE(${var_name}_pri)",
		rcr			=> sprintf("0x%04X", $info->{cr}),
		ecr			=> sprintf("0x%04X", $info->{ehcr}),
	);

	my @flash_table;
	for (my $i = 0; $i < scalar(@flash_struct); $i += 2) {
		push @flash_table, [".".$flash_struct[$i], "= ".$flash_struct[$i + 1].","];
	}

	push @flashes, "\t{\n".printTable(\@flash_table, "\t\t")."\t},";
}

print "static const CFIFlashChip flashes[] = {\n";
print join("\n", @flashes)."\n";
print "};\n";

print qq|
const CFIFlashChip *cfi_flash_find_chip(uint16_t vid, uint16_t pid) {
	for (size_t i = 0; i < ARRAY_SIZE(flashes); i++) {
		if (flashes[i].vid == vid && flashes[i].pid == pid)
			return &flashes[i];
	}
	return NULL;
}
|;

select STDOUT;
close $output_fp;
print tabsToSpaces($output);

sub dumpHex {
	my ($tab, $bin) = @_;
	my @lines;
	my @line;
	for (my $i = 0; $i < length($bin); $i++) {
		push @line, sprintf("0x%02X", ord(substr($bin, $i, 1)));
		if (scalar(@line) >= 16) {
			push @lines, [@line];
			@line = ();
		}
	}
	push @lines, [@line] if scalar(@line) > 0;
	return $tab.join("\n$tab", map { join(", ", @$_)."," } @lines)."\n";
}
